  // Language persists in localStorage so the correct UI renders before the
  // async /api/settings fetch resolves (kills the English flash on page loads).
  const LANG_KEY = 'mizan_lang';
  function readCachedLang() {
    try { return localStorage.getItem(LANG_KEY) || ''; } catch (e) { return ''; }
  }
  function writeCachedLang(l) {
    try { localStorage.setItem(LANG_KEY, l); } catch (e) { /* ignore */ }
  }
  function normalizeLang(l) {
    return l === 'fr' ? 'fr' : (l === 'ar' ? 'ar' : 'en');
  }

  const cached = normalizeLang(readCachedLang());
  if (cached !== 'en' || lang !== cached) lang = cached;
  document.documentElement.lang = lang;
