  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = t(key);
      if (el.tagName === 'INPUT') {
        el.placeholder = val;
      } else {
        const icon = el.querySelector(':scope > [data-icon]');
        if (icon) {
          while (icon.nextSibling) icon.parentNode.removeChild(icon.nextSibling);
          icon.parentNode.insertBefore(document.createTextNode(' ' + val), icon.nextSibling);
        } else {
          el.textContent = val;
        }
      }
    });
    // Translate title / aria-label attributes: <button data-i18n-title="key">.
    scope.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    scope.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
    });
    if (document.title && document.title.indexOf('-') !== -1) {
      document.title = document.title.split('-')[0].trim() + ' - ' + t(document.body.dataset.i18nTitle || document.title.split('-')[1].trim());
    }
  }

  async function load() {
    try {
      const res = await fetch('/api/settings');
      const s = await res.json();
      lang = normalizeLang(s.language);
    } catch (e) { /* keep default */ }
    writeCachedLang(lang);
    applyDirection();
    document.documentElement.lang = lang;
    apply();
    if (window.renderProducts) window.renderProducts();
    if (window.AK_AUTH) {
      window.AK_AUTH.then(() => {
        if (window.renderSidebar) window.renderSidebar();
      });
    }
    window.dispatchEvent(new Event('languagechange'));
  }

  function setLang(l) {
    lang = normalizeLang(l);
    writeCachedLang(lang);
    applyDirection();
    document.documentElement.lang = lang;
    apply();
    window.dispatchEvent(new Event('languagechange'));
  }

  // Arabic is right-to-left; flip the document direction so layout mirrors.
  function applyDirection() {
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }

